// Refresh src/data/statcan-latest.js from Statistics Canada's newest release
// of Table 18-10-0245-01. Run by .github/workflows/update-prices.yml each
// month; safe to run by hand: `node scripts/update-prices.js`.
//
// Data: Statistics Canada, Open Licence
// https://www.statcan.gc.ca/en/terms-conditions/open-licence

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { latestCanadaPrices } from './statcan.js';
import { STATCAN_PRICES } from '../src/data/statcan-latest.js';
import { DEFAULT_PRICES } from '../src/data/prices.js';

// The Web Data Service returns the current download link for the full table.
// https://www.statcan.gc.ca/en/developers/wds/user-guide
const WDS_URL = 'https://www150.statcan.gc.ca/t1/wds/rest/getFullTableDownloadCSV/18100245/en';
const FALLBACK_ZIP_URL = 'https://www150.statcan.gc.ca/n1/tbl/csv/18100245-eng.zip';
const OUT = fileURLToPath(new URL('../src/data/statcan-latest.js', import.meta.url));

async function zipUrl() {
  try {
    const r = await fetch(WDS_URL);
    const json = await r.json();
    if (json.status === 'SUCCESS' && json.object) return json.object;
  } catch (err) {
    console.warn('WDS lookup failed, using the usual link', err.message);
  }
  return FALLBACK_ZIP_URL;
}

const res = await fetch(await zipUrl());
if (!res.ok) throw new Error(`Download failed: ${res.status}`);
const dir = mkdtempSync(join(tmpdir(), 'statcan-'));
const zip = join(dir, 'table.zip');
writeFileSync(zip, Buffer.from(await res.arrayBuffer()));
execFileSync('unzip', ['-o', '-q', zip, '-d', dir]);
const csv = readdirSync(dir).find((f) => /^18100245\.csv$/i.test(f));
if (!csv) throw new Error('Data CSV not found in the zip');

const latest = latestCanadaPrices(readFileSync(join(dir, csv), 'utf8'));
const wanted = DEFAULT_PRICES.map((p) => p.statcan);
const found = wanted.filter((label) => Number.isFinite(latest.prices[label]));
console.log(`StatCan month ${latest.month}: ${found.length}/${wanted.length} app items found`);
if (found.length < wanted.length * 0.8) throw new Error('Too many items missing; the table layout may have changed. Not updating.');

if (latest.month <= STATCAN_PRICES.month) {
  console.log(`Already up to date (${STATCAN_PRICES.month}).`);
  process.exit(0);
}

// Keep last month's value for anything StatCan didn't publish this month.
const prices = Object.fromEntries(wanted.map((label) => [label, latest.prices[label] ?? STATCAN_PRICES.prices[label]]));
const body = `// Generated by scripts/update-prices.js from Statistics Canada Table 18-10-0245-01
// (geography: Canada). Do not edit by hand; the monthly GitHub Action rewrites it.
// Source: Statistics Canada, Table 18-10-0245-01 Monthly average retail prices for selected products.

export const STATCAN_PRICES = ${JSON.stringify({ month: latest.month, updated: new Date().toISOString().slice(0, 10), prices }, null, 2)};
`;
writeFileSync(OUT, body);
console.log(`Updated to ${latest.month}.`);
